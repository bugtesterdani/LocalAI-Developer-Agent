"""Erzeugt C#-Records und Pydantic-Modelle aus contracts/schemas/contracts.schema.json.

Unterstützte Schema-Teilmenge (bewusst klein gehalten):
  type: string | integer | boolean | object (frei) | array (items) ; enum (string) ; $ref auf #/$defs/X
  format: date-time (bleibt string)

Aufruf:
  python tools/codegen/generate.py          # Dateien schreiben
  python tools/codegen/generate.py --check  # nur prüfen, ob die Dateien aktuell sind (Exitcode 1 sonst)
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "contracts" / "schemas" / "contracts.schema.json"
CS_OUT = ROOT / "src" / "dotnet" / "LocalAi.Contracts" / "Generated" / "Contracts.g.cs"
PY_OUT = ROOT / "src" / "python" / "localai" / "contracts" / "generated.py"

HEADER = "Automatisch erzeugt aus contracts/schemas/contracts.schema.json – nicht von Hand ändern."


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


# ---------------------------------------------------------------- C#

def cs_type(prop: dict) -> str:
    if "$ref" in prop:
        return ref_name(prop["$ref"])
    t = prop["type"]
    if t == "string":
        return "string"
    if t == "integer":
        return "long"
    if t == "boolean":
        return "bool"
    if t == "object":
        return "JsonElement"
    if t == "array":
        return f"IReadOnlyList<{cs_type(prop['items'])}>"
    raise ValueError(f"Typ nicht unterstützt: {t}")


def gen_cs(defs: dict) -> str:
    lines = [
        f"// <auto-generated>{HEADER}</auto-generated>",
        "#nullable enable",
        "using System.Collections.Generic;",
        "using System.Text.Json;",
        "using System.Text.Json.Serialization;",
        "",
        "namespace LocalAi.Contracts;",
        "",
    ]
    for name, d in defs.items():
        if "enum" in d:
            lines.append(f"[JsonConverter(typeof(JsonStringEnumConverter<{name}>))]")
            lines.append(f"public enum {name}")
            lines.append("{")
            lines += [f"    {v}," for v in d["enum"]]
            lines.append("}")
            lines.append("")
            continue
        if d.get("description"):
            lines.append(f"/// <summary>{d['description']}</summary>")
        props = d["properties"]
        required = d.get("required", [])
        ordered = [p for p in props if p in required] + [p for p in props if p not in required]
        params = []
        for p in ordered:
            t = cs_type(props[p])
            if p in required:
                params.append(f'    [property: JsonPropertyName("{p}")] {t} {pascal(p)}')
            else:
                params.append(f'    [property: JsonPropertyName("{p}"), JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] {t}? {pascal(p)} = null')
        lines.append(f"public sealed partial record {name}(")
        lines.append(",\n".join(params) + ");")
        lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------- Python

def py_type(prop: dict) -> str:
    if "$ref" in prop:
        return ref_name(prop["$ref"])
    t = prop["type"]
    if t == "string":
        return "str"
    if t == "integer":
        return "StrictInt"
    if t == "boolean":
        return "StrictBool"
    if t == "object":
        return "dict[str, Any]"
    if t == "array":
        return f"list[{py_type(prop['items'])}]"
    raise ValueError(f"Typ nicht unterstützt: {t}")


def gen_py(defs: dict) -> str:
    lines = [
        f'"""{HEADER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "from typing import Any",
        "",
        "from pydantic import BaseModel, ConfigDict, Field, StrictBool, StrictInt",
        "",
        "",
        "class Contract(BaseModel):",
        '    model_config = ConfigDict(extra="forbid", populate_by_name=True, frozen=True)',
        "",
        "    def to_json_obj(self) -> dict[str, Any]:",
        '        """JSON-Form wie in C#: camelCase, None-Felder weggelassen."""',
        '        return self.model_dump(mode="json", by_alias=True, exclude_none=True)',
        "",
    ]
    for name, d in defs.items():
        lines.append("")
        if "enum" in d:
            lines.append(f"class {name}(str, Enum):")
            lines += [f'    {v} = "{v}"' for v in d["enum"]]
            lines.append("")
            continue
        lines.append(f"class {name}(Contract):")
        if d.get("description"):
            lines.append(f'    """{d["description"]}"""')
            lines.append("")
        required = d.get("required", [])
        for p, prop in d["properties"].items():
            t = py_type(prop)
            if p in required:
                lines.append(f'    {snake(p)}: {t} = Field(alias="{p}")')
            else:
                lines.append(f'    {snake(p)}: {t} | None = Field(default=None, alias="{p}")')
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    defs = schema["$defs"]
    outputs = {CS_OUT: gen_cs(defs), PY_OUT: gen_py(defs)}
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if check and stale:
        for p in stale:
            print(f"veraltet: {p.relative_to(ROOT)}")
        return 1
    print("aktuell" if check else f"geschrieben: {len(stale)} Datei(en)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
